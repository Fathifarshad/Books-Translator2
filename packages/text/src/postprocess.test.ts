describe('postprocess — segment types and other languages', () => {
  it('never changes code segments', () => {
    const code = 'for i in range(3):\n    print(i, "done?")';
    expect(postprocess(code, 'fa', { segmentType: 'code' })).toBe(code);
  });

  it('keeps line breaks inside multi-line segments', () => {
    expect(postprocess('خط اول  \n  خط دوم', 'fa')).toBe('خط اول\nخط دوم');
  });

  it('languages without a normalizer only get whitespace cleanup', () => {
    expect(postprocess('  Hello,   world?  ', 'en')).toBe('Hello, world?');
    expect(postprocess('  Hola,   mundo  ', 'xx')).toBe('Hola, mundo');
  });

  it('is idempotent', () => {
    const inputs = [
      'این روش کار می کند, و "کتاب ها" 3.5 درصد',
      'ایده ی اصلی (Main Idea) در شکل 3.1',
      'آن ها 1,200 صفحه دارند?',
    ];
    for (const input of inputs) {
      const once = postprocess(input, 'fa');
      expect(postprocess(once, 'fa')).toBe(once);
    }
  });
});

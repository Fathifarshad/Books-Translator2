import { describe, expect, it } from 'vitest';
import { type PostprocessOptions, postprocess } from './postprocess';

/** `~` marks a ZWNJ in expectations so the tables stay readable. */
const z = (s: string) => s.replaceAll('~', '\u{200C}');

type Case = [input: string, expected: string, options?: PostprocessOptions];

const run = (cases: Case[]) =>
  it.each(cases)('%s', (input, expected, options) => {
    expect(postprocess(z(input), 'fa', options)).toBe(z(expected));
  });

describe('postprocess fa — characters', () => {
  run([
    ['كتاب', 'کتاب'],
    ['يك روز', 'یک روز'],
    ['مسئله‌اي مهم', 'مسئله~ای مهم'],
    ['موسى و عيسى', 'موسی و عیسی'],
    ['بـــزرگ', 'بزرگ'],
    ['خانە', 'خانه'],
    ['ﻛﺘﺎﺏ', 'کتاب'],
    ['  فاصله‌های   اضافه  ', 'فاصله~های اضافه'],
    ['متن\tبا\tتب', 'متن با تب'],
    ['نیم\u{00A0}فاصله‌ی سخت', 'نیم فاصله~ی سخت'],
  ]);
});

